import time
import json
import statistics
import sys
from pathlib import Path
from typing import List, Dict, Any

# Ensure project root is in sys.path
BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from graph import app_graph

BENCHMARK_QUERIES = [
    # 1. Basic Aggregation & Filtering
    "What is the total count of active customers in the database?",
    "How many total orders have been placed with status 'completed'?",
    "What is the average discount percentage applied across all order items?",
    "How many total products are currently available in the Electronics category?",
    "What is the total sum of all order items before discounts are applied?",

    # 2. Group By & Category Aggregations
    "What is the total net revenue generated by each product category?",
    "Which 5 customer cities have generated the highest total order revenue?",
    "What is the total quantity of items sold per customer tier (Enterprise, SMB, Startup)?",
    "How many orders were placed via each payment method (Credit Card, UPI, Net Banking)?",
    "What is the breakdown of order statuses (completed, shipped, processing, cancelled)?",

    # 3. Multi-table Joins
    "List the top 5 customers by total spending with their name, email, and total spent.",
    "Which products have never been ordered?",
    "Find the top 3 best-selling products by quantity sold along with their categories.",
    "What is the total revenue lost to returns per return reason?",
    "Which customers have placed more than 3 completed orders?",

    # 4. Complex Business Logic & Calculations
    "What is the average order value (AOV) across all completed orders?",
    "Calculate the net revenue per month for the year 2024.",
    "What percentage of total orders have at least one return request?",
    "Which product has the highest return rate by quantity?",
    "What is the total discount amount given to Enterprise tier customers?",

    # 5. Advanced Analysis & Rankings
    "Rank the top sales representative cities by total order volume.",
    "Find the most expensive product purchased in the 'Furniture' category.",
    "What is the average shipping days between order date and ship date for completed orders?",
    "Which customer has the highest number of returned items?",
    "What is the overall repeat customer rate (customers with 2 or more orders)?"
]


def run_benchmark():
    print(f"============================================================", flush=True)
    print(f"Starting InsightSQL 25-Query Autonomous Benchmark Suite", flush=True)
    print(f"Model Under Test: LangGraph + Dynamic LLM (Groq / GPT-OSS-120B)", flush=True)
    print(f"Database: SQLite BI Warehouse (Customers, Orders, Items, Returns)", flush=True)
    print(f"============================================================\n", flush=True)

    results: List[Dict[str, Any]] = []
    latencies: List[float] = []
    first_pass_count = 0
    healed_count = 0
    failed_count = 0

    for idx, query in enumerate(BENCHMARK_QUERIES, 1):
        print(f"[{idx:02d}/25] Query: {query}", flush=True)
        t0 = time.perf_counter()
        
        try:
            state = app_graph.invoke({"question": query, "skip_synthesis": True})
            elapsed = time.perf_counter() - t0
            latencies.append(elapsed)

            has_error = state.get("error_message") is not None
            was_healed = state.get("was_self_healed", False)
            rows = len(state.get("query_result", []))

            if has_error:
                status = "FAILED"
                failed_count += 1
            elif was_healed:
                status = "SELF_HEALED"
                healed_count += 1
            else:
                status = "FIRST_PASS"
                first_pass_count += 1

            sql_snippet = state.get("sql_query", "").replace("\n", " ")[:60]
            print(f"       -> Status: {status} | Time: {elapsed:.2f}s | Rows: {rows} | SQL: {sql_snippet}...", flush=True)

            results.append({
                "id": idx,
                "question": query,
                "status": status,
                "latency_sec": round(elapsed, 3),
                "rows_retrieved": rows,
                "was_self_healed": was_healed,
                "sql": state.get("sql_query"),
                "summary": state.get("executive_summary")
            })

        except Exception as e:
            elapsed = time.perf_counter() - t0
            latencies.append(elapsed)
            failed_count += 1
            print(f"       -> EXCEPTION: {e} | Time: {elapsed:.2f}s", flush=True)
            results.append({
                "id": idx,
                "question": query,
                "status": "EXCEPTION",
                "latency_sec": round(elapsed, 3),
                "error": str(e)
            })

        # Small cooldown between requests to respect OpenRouter rate limits
        time.sleep(0.5)

    total_queries = len(BENCHMARK_QUERIES)
    successful_queries = first_pass_count + healed_count
    success_rate = (successful_queries / total_queries) * 100
    first_pass_rate = (first_pass_count / total_queries) * 100

    p50 = statistics.median(latencies) if latencies else 0
    sorted_lats = sorted(latencies)
    p95_idx = int(0.95 * len(sorted_lats))
    p95 = sorted_lats[p95_idx] if sorted_lats else 0
    avg_lat = statistics.mean(latencies) if latencies else 0

    print("\n============================================================", flush=True)
    print("INSIGHTSQL BENCHMARK SUMMARY REPORT", flush=True)
    print("============================================================", flush=True)
    print(f"Total Queries Evaluated: {total_queries}", flush=True)
    print(f"Successful Executions:   {successful_queries}/{total_queries} ({success_rate:.1f}%)", flush=True)
    print(f"  - First-Pass Success:  {first_pass_count}/{total_queries} ({first_pass_rate:.1f}%)", flush=True)
    print(f"  - Self-Healed Recover: {healed_count}/{total_queries} ({(healed_count/total_queries)*100:.1f}%)", flush=True)
    print(f"  - Unrecoverable Fails: {failed_count}/{total_queries}", flush=True)
    print(f"Latency P50:             {p50:.2f}s", flush=True)
    print(f"Latency P95:             {p95:.2f}s", flush=True)
    print(f"Latency Avg:             {avg_lat:.2f}s", flush=True)
    print("============================================================\n", flush=True)

    # Save benchmark data to json
    out_dir = Path(__file__).resolve().parent.parent / "benchmark_results"
    out_dir.mkdir(exist_ok=True)
    out_file = out_dir / "benchmark_run.json"
    
    summary_data = {
        "total_queries": total_queries,
        "successful_queries": successful_queries,
        "success_rate_pct": round(success_rate, 2),
        "first_pass_count": first_pass_count,
        "first_pass_pct": round(first_pass_rate, 2),
        "healed_count": healed_count,
        "failed_count": failed_count,
        "p50_seconds": round(p50, 3),
        "p95_seconds": round(p95, 3),
        "avg_seconds": round(avg_lat, 3),
        "runs": results
    }
    
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2)
    print(f"Benchmark results successfully written to: {out_file}")


if __name__ == "__main__":
    run_benchmark()
