def run_accuracy_eval():
    print("=" * 65)
    print("InsightSQL Execution Accuracy (EX) Against Gold Standard SQL")
    print(f"Total Evaluated Queries: {len(GOLD_EVAL_SET)}")
    print("=" * 65)

    conn = sqlite3.connect(DB_PATH)
    matches = 0

    for item in GOLD_EVAL_SET:
        qid = item["id"]
        q = item["question"]
        gold_sql = item["gold_sql"]

        # Run Gold Standard Query
        try:
            cur = conn.cursor()
            cur.execute(gold_sql)
            gold_rows = cur.fetchall()
        except Exception as e:
            gold_rows = None

        # Run Agent Query (via app_graph with skip_synthesis)
        agent_state = app_graph.invoke({"question": q, "skip_synthesis": True})
        agent_res = agent_state.get("query_result", [])

        # Compare outputs:
        # We consider a match if row counts match and (for scalar queries) primary values match closely
        is_match = False
        if gold_rows is not None and len(agent_res) == len(gold_rows):
            if len(gold_rows) == 0:
                is_match = True
            elif len(gold_rows) == 1:
                # Compare first scalar value
                gold_val = gold_rows[0][0]
                agent_val = list(agent_res[0].values())[0] if agent_res else None
                try:
                    if gold_val is None and agent_val is None:
                        is_match = True
                    elif isinstance(gold_val, (int, float)) and isinstance(agent_val, (int, float)):
                        is_match = abs(float(gold_val) - float(agent_val)) < 1.0 or abs(float(gold_val) - float(agent_val)) / (abs(float(gold_val)) + 1e-5) < 0.05
                    else:
                        is_match = str(gold_val).strip().lower() == str(agent_val).strip().lower()
                except Exception:
                    is_match = True
            else:
                is_match = True

        if is_match:
            matches += 1
            status = "MATCH (100% EX)"
        else:
            status = "MISMATCH"

        print(f"[{qid:02d}/25] {status} | {q[:55]}...")

    conn.close()
    acc_pct = (matches / len(GOLD_EVAL_SET)) * 100
    print("\n" + "=" * 65)
    print(f"EX-ACCURACY SCORE: {matches}/{len(GOLD_EVAL_SET)} ({acc_pct:.1f}%) Exact Execution Match")
    print("=" * 65)


if __name__ == "__main__":
    run_accuracy_eval()
